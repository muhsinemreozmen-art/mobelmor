conn = sqlite3.connect('database/mobelmor.db')
cursor = conn.cursor()
cursor.execute("DELETE FROM products;")
for p in CORRECTED_CATALOG:
    cursor.execute("""
        INSERT INTO products (
            id, title, slug, category_slug, subcategory_slug, product_type, price, old_price, rating, reviews_count, main_image, material, description
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        p['id'],
        p['title'],
        p['title'].lower().replace(' ', '-').replace('&', 've'),
        p['category'],
        p.get('subcategory', ''),
        p.get('productType', 'Solo'),
        p['price'],
        p.get('originalPrice', 0),
        p.get('rating', 4.9),
        p.get('reviewsCount', 25),
        p['image'],
        p.get('material', ''),
        p.get('desc', '')
    ))
